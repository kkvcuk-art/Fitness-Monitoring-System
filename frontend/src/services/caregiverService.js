const CONTACTS_KEY = "phc_caregiver_contacts_v1";
const ALERTS_KEY = "phc_emergency_alerts_v1";
const CONSENT_KEY = "phc_caregiver_sharing_consent_v1";

function read(key, fallback) {
  try { return JSON.parse(localStorage.getItem(key) || "null") ?? fallback; }
  catch { return fallback; }
}
function write(key, value) { localStorage.setItem(key, JSON.stringify(value)); }

export function getCaregiverContacts() { return read(CONTACTS_KEY, []); }
export function saveCaregiverContacts(contacts) { write(CONTACTS_KEY, contacts); }
export function getSharingConsent() { return read(CONSENT_KEY, false) === true; }
export function setSharingConsent(enabled) { write(CONSENT_KEY, Boolean(enabled)); }
export function getEmergencyAlerts() { return read(ALERTS_KEY, []); }
export function recordEmergencyAlert(alert) {
  const next = [{ ...alert, id: crypto.randomUUID?.() || `${Date.now()}`, createdAt: new Date().toISOString() }, ...getEmergencyAlerts()].slice(0, 50);
  write(ALERTS_KEY, next);
  return next[0];
}
export function clearEmergencyAlerts() { write(ALERTS_KEY, []); }

export function buildEmergencySummary({ patientName = "User", riskLevel = "UNKNOWN", riskScore, reason = "Emergency assistance requested", location }) {
  const lines = [
    "PERSONAL HEALTH COMPANION — EMERGENCY ALERT",
    `Patient: ${patientName}`,
    `Risk: ${riskLevel}${Number.isFinite(riskScore) ? ` (${Math.round(riskScore)}%)` : ""}`,
    `Reason: ${reason}`,
    location?.mapsUrl ? `Location: ${location.mapsUrl}` : "Location: Not shared",
    "This alert was generated by the user's Personal Health Companion.",
  ];
  return lines.join("\n");
}
